// Generates src/abis.ts from Foundry build output (run `forge build` in contracts/ first).
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../../contracts/out");
const contracts = {
  mandateAccountAbi: "MandateAccount.sol/MandateAccount.json",
  mandateRegistryAbi: "MandateRegistry.sol/MandateRegistry.json",
  mandateAccountFactoryAbi: "MandateAccountFactory.sol/MandateAccountFactory.json",
  perplAdapterAbi: "PerplAdapter.sol/PerplAdapter.json",
  perplExchangeAbi: "IPerplExchange.sol/IPerplExchange.json",
};

let out = "// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit.\n";
for (const [name, file] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(join(root, file), "utf8"));
  out += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
// Perpl custom errors, from dex-sdk (contracts/abi/PerplErrors.json), to decode exchange reverts.
const errs = JSON.parse(readFileSync(join(root, "../abi/PerplErrors.json"), "utf8"));
out += `
export const perplErrorsAbi = ${JSON.stringify(errs.abi ?? errs, null, 2)} as const;
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "../src/abis.ts"), out);
console.log("wrote src/abis.ts");
